# ── Обратный индекс: дефект → список МКБ-кодов ───────────────────────────────
ICD10_BY_DEFECT: dict[str, list[str]] = {}
for _icd_code, _entry in ICD10_CODES.items():
    for _defect in _entry['defect_codes']:
        ICD10_BY_DEFECT.setdefault(_defect, []).append(_icd_code)


def get_icd_codes_for_defects(defect_codes: list[str]) -> dict[str, list[dict]]:
    """
    Возвращает словарь: код_дефекта → список МКБ-объектов.
    Используется фронтендом для построения фильтрованного выпадающего списка.

    Пример:
      get_icd_codes_for_defects(['1', '3']) →
      {
        '1': [{'code': 'К06.00', 'title': 'Рецессия десны. Локальная'}, ...],
        '3': [{'code': 'К03.2',  'title': 'Эрозия зубов'}, ...],
      }
    """
    result = {}
    for defect in defect_codes:
        codes = ICD10_BY_DEFECT.get(str(defect), [])
        result[str(defect)] = [
            {'code': c, 'title': ICD10_CODES[c]['title']}
            for c in codes
        ]
    return result


def validate_icd_code(code: str, defect_codes: list[str]) -> bool:
    """
    Проверяет, что МКБ-код допустим хотя бы для одного из указанных дефектов.
    """
    entry = ICD10_CODES.get(code)
    if not entry:
        return False
    return any(d in entry['defect_codes'] for d in defect_codes)